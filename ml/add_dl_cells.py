        "            print(f'  Epoch {epoch+1:3d} | Train: {avg_train:.4f} | Val: {avg_val:.4f}')\n",
        "\n",
        "    # Load best weights\n",
        "    if best_state is not None:\n",
        "        model.load_state_dict(best_state)\n",
        "\n",
        "    return model, history\n",
